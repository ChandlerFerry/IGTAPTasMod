#!/usr/bin/env python3
"""Turn ilspycmd output of Unity's managed math types into shim sources.

Unity's value types (Vector2, Mathf, ...) are plain managed code; the shim uses Unity's exact implementations so
float results match the game bit for bit. This strips engine-only attributes and drops members that call into
native code (extern), which the game never reaches.

usage: sanitize-unity.py <decompiled.cs> <out.cs>
"""
import re
import sys

ENGINE_ATTRIBUTES = re.compile(
    r"^\s*\[(NativeClass|NativeHeader|NativeType|NativeMethod|NativeName|FreeFunction|StaticAccessor|ThreadSafe|"
    r"RequiredByNativeCode|UsedByNativeCode|Il2CppEagerStaticClassConstruction|VisibleToOtherModules|"
    r"ExcludeFromDocs|MovedFrom|NativeConditional|Obsolete|DefaultValue|Preserve|GeneratedByOldBindingsGenerator|"
    r"IsReadOnly|NativeThrows|NativeAsStruct|Ignore)\b.*\]\s*$")
USINGS = re.compile(r"^using (Unity\.IL2CPP\.CompilerServices|UnityEngine\.Internal|UnityEngine\.Scripting|UnityEngine\.Bindings|"
                    r"Unity\.Burst|UnityEngine\.Scripting\.APIUpdating|Unity\.Collections\.LowLevel\.Unsafe|UnityEngineInternal);\s*$")
INLINE_ATTRIBUTES = re.compile(r"\[DefaultValue\([^)]*\)\]\s*")


def members(lines):
    """Split a class body into top-level member chunks by brace depth (depth 1 inside the type)."""
    out, chunk, depth = [], [], 0
    for line in lines:
        chunk.append(line)
        depth += line.count("{") - line.count("}")
        stripped = line.strip()
        if depth == 1 and (stripped.endswith("}") or stripped.endswith(";")) or depth == 0:
            out.append(chunk)
            chunk = []
    if chunk:
        out.append(chunk)
    return out


def main(src, dst):
    text = [l for l in open(src, encoding="utf-8").read().splitlines()
            if not l.startswith("You are not using the latest version") and not l.startswith("Latest version is")]
    kept = [INLINE_ATTRIBUTES.sub("", l) for l in text if not ENGINE_ATTRIBUTES.match(l) and not USINGS.match(l)]
    # File-scoped namespace (ilspy style): header lines until the first type declaration.
    first = next(i for i, l in enumerate(kept) if re.match(r"^(public|internal)\s", l))
    header, body = kept[:first], kept[first:]
    result = []
    for chunk in members(body):
        joined = "\n".join(chunk)
        if " extern " in joined and "{" not in joined.split(" extern ", 1)[1].split(";")[0]:
            continue
        result.extend(chunk)
    open(dst, "w", encoding="utf-8").write("// Generated by enginesim/tools/sanitize-unity.py from UnityEngine (6000.3.17f1).\n"
                                           + "\n".join(header + result) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
